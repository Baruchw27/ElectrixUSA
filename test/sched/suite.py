from harness import *
SEED=json.load(open(os.path.join(HERE,'seed_prod.json')))
def net(m): urllib.request.urlopen(BASE+'/__net?mode='+m)
def sched(id=None):
    rs=[r for r in srv('/__records?coll=sched') if not r['deleted']]
    return {r['id']:r['data'] for r in rs} if id is None else next((r['data'] for r in rs if r['id']==id),None)
def sites_of(d): return sorted((a['site'],a['start'],a.get('end')) for a in (d or {}).get('assignments',[]))
async def ready(P): await until(P,"EX_ready&&EX_ready()",12000)
async def settle(P,ms=8000): return await until(P,"!EX_SYNC.pending&&!EX_SYNC.flushing",ms)
async def toasts(P): return await P.evaluate("window._t||[]")
async def clear_toasts(P): await P.evaluate("window._t=[]")
async def open_day(P,crew,k): await P.evaluate(f"editSlot('{crew}','{k}')"); await P.wait_for_timeout(150)
async def add_full(P,site):
    await P.evaluate(f"slotPickMode('menu')"); await P.select_option('#slotAddSite',site); await P.click("#slotBody button:has-text('Full day')"); await P.wait_for_timeout(100)
async def add_hours(P,site,h):
    await P.evaluate("slotPickMode('menu')"); await P.select_option('#slotAddSite',site); await P.click("#slotBody button:has-text('Specific hours')"); await P.fill('#slotAddHours',str(h)); await P.click("#slotBody button:has-text('Add')"); await P.wait_for_timeout(100)
async def tap_save(P): await P.click("#slotBody button.btn[onclick='saveSlot()']")
async def modal_open(P,id='m-slot'): return await P.evaluate(f"!document.getElementById('{id}').classList.contains('hid')")
async def day(P,off): return await P.evaluate(f"(()=>{{const d=new Date();d.setDate(d.getDate()+{off});return dkey(d)}})()")
