# Scanner V2 — every screen flow in a real browser (Chromium, phone size), against the STAGING app file.
import asyncio, json, os, sys
from playwright.async_api import async_playwright
HERE = os.path.dirname(os.path.abspath(__file__))
F = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'staging', 'index.html')
SHOTS = os.path.join(HERE, 'out', 'shots'); os.makedirs(SHOTS, exist_ok=True)
INIT = """window.EX_fakeScan=(v,cb)=>{window._scan=cb;return ()=>{};};
navigator.mediaDevices=navigator.mediaDevices||{};navigator.mediaDevices.getUserMedia=async()=>{const c=document.createElement('canvas');c.width=640;c.height=480;const g=c.getContext('2d');setInterval(()=>{g.fillStyle='#ccc';g.fillRect(0,0,640,480)},100);return c.captureStream(10);};"""
ok = []; bad = []
def chk(n, c, extra=''):
    (ok if c else bad).append(n + ('' if c else '  ' + str(extra)[:200])); print(('  ✓ ' if c else '  ✗ ') + n + ('' if c else '  ' + str(extra)[:200]))
def ck(b): s = sum(int(d) * (3 if i % 2 == 0 else 1) for i, d in enumerate(reversed(b))); return str((10 - s % 10) % 10)
U3 = '07847710037'; U3 += ck(U3)           # Leviton 3-way single
U4 = '07847710038'; U4 += ck(U4)           # neighbour number (different product)
B3 = '2007847710037'; B3 += ck(B3)         # box of the 3-way
UL = '79388842694'; UL += ck(UL)           # Luxrite
UX = '61234500012'; UX += ck(UX)           # unknown maker
SW_TXT = "QTY\nQTE\nCANT 10\n5603-2W\nWHITE / BLANC / BLANCO\n3-WAY SWITCH GROUNDING UL CSA NOM\nINTERRUPTEUR A 3-VOIES\nLEVITON"
LUX_TXT = "LUXRITE\n2\" ROUND WHITE\nTRIM REPLACEMENT\nITEM# LR25022\nLED/DLMD2/TRIM/RD/WT\nMADE IN CHINA"
JUNK_TXT = "BEA IMR M00 & EER\nAlm Cries UU\n|| ~ ee\n"
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); ctx = await b.new_context(viewport={'width': 390, 'height': 844}); await ctx.add_init_script(INIT)
        pg = await ctx.new_page(); errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.route('**/*', lambda r: r.abort() if r.request.url.startswith('http') else r.continue_())
        E = pg.evaluate; await pg.goto('file://' + F); await pg.wait_for_timeout(700)
        await E("""window._upcCalls=[];window._ocrCalls=0;window._UPCDB={};window.EX_upc=async c=>{_upcCalls.push(c);return _UPCDB[c]||{found:false};};
          window._OCR='';window.ocrText=async()=>{_ocrCalls++;return _OCR};window._t=[];const ot=toast;toast=function(a){_t.push(String(a));return ot.apply(this,arguments)};0""")
        await E("signIn('u1');setRole(D.emps.find(e=>e.name==='Jon').id);document.querySelectorAll('.ov').forEach(o=>o.classList.add('hid'));0")
        async def open_scan(mode='in'):
            await E(f"scanQuick('{mode}');0"); await pg.wait_for_timeout(1500)
        async def scan(code, fmt=''):
            await E(f"scM&&(scM.pausedCode=null,scM.last='',scM.lastT=0);_scan('{code}','{fmt}');0"); await pg.wait_for_timeout(500)
        sheet = lambda: E("(document.getElementById('scSheet')||{}).innerText||''")
        async def shot(n): await pg.screenshot(path=os.path.join(SHOTS, n + '.png'))
        await open_scan('in')
        chk('V2 scanner is active on staging', await E("!!window.SV2_UI&&SV2_UI.version==='v2.0'"))

        print('1. Bad read (check digit wrong) is refused, nothing guessed')
        badc = U3[:-1] + str((int(U3[-1]) + 3) % 10)
        await scan(badc)
        chk('warns to scan again', 'did not read cleanly' in await E("document.getElementById('scHint').innerText"))
        chk('no item sheet, scanner keeps going', await E("!scM.pausedCode&&!document.getElementById('scSheet').classList.contains('on')"))

        print('2. Brand-new barcode, found in an online product database')
        await E(f"_UPCDB['{U3[1:]}']=_UPCDB['0{U3}']={{found:true,title:'Leviton 5603-2W Decora 15 Amp 3-Way Rocker Switch, White',brand:'Leviton',model:'5603-2W'}};_OCR={json.dumps(SW_TXT)};0")
        before = await E("D.stock.length")
        await scan(U3, 'upc_a'); await pg.wait_for_timeout(600)
        s = await sheet(); await shot('02_new_online')
        chk('looked the barcode up online', await E("_upcCalls.length")>=1, await E("_upcCalls"))
        chk('proposes maker + part from the online database', await E("document.getElementById('v2b').value==='Leviton'&&document.getElementById('v2p').value==='5603-2W'"), s)
        chk('nothing saved before the person taps', await E("D.stock.length") == before)
        await pg.locator('#scLook .btn.gr').click(); await pg.wait_for_timeout(300)
        chk('new item saved with maker + part number', await E("D.stock.some(x=>x.model==='5603-2W'&&x.brand==='Leviton')"))
        nid = await E("D.stock.find(x=>x.model==='5603-2W').id")
        chk('new item id comes from the barcode (same on every phone)', nid.startswith('s_bc') and U3 in nid, nid)
        chk('barcode link saved as its own record', await E(f"Object.values(D.bc).some(m=>m.item==='{nid}'&&m.pack===1&&m.verified)"))
        await pg.locator('#scQok').click(); await pg.wait_for_timeout(200)
        chk('counted 1', await E(f"siLines.find(l=>l.id==='{nid}').qty===1"))

        print('3. Confirmed barcode → instant, offline, no lookups')
        await E("_upcCalls=[];_ocrCalls=0;window.EX_SYNC={online:false};0")
        await scan(U3); s = await sheet()
        chk('instant "how many"', 'How many are you putting back?' in s, s[:200])
        chk('no online lookup and no label reading', await E("_upcCalls.length===0&&_ocrCalls===0"))
        chk('shows what is already in this list', 'Already in this list' in s)
        await E("scQ(0,5);0"); await pg.locator('#scQok').click(); await pg.wait_for_timeout(200)
        chk('adds 5 → 6 in the list (no double count)', await E(f"siLines.find(l=>l.id==='{nid}').qty===6"))
        await E("window.EX_SYNC={online:true};0")

        print('4. Same number family (box of 10) → asks, never assumes')
        await scan(B3, 'itf'); s = await sheet(); await shot('04_family')
        chk('box barcode recognized', 'box barcode' in s.lower())
        chk('asks "looks like the BOX of" the known item', 'BOX of an item you already have' in s and '5603-2W' in s, s[:300])
        chk('nothing linked yet', await E(f"!Object.values(D.bc).some(m=>m.code==='{B3}')"))
        await pg.locator('#scSheet .v2c').first.click(); await pg.wait_for_timeout(200)
        chk('then asks how many are in one box', 'How many are in ONE box?' in await sheet())
        await E("document.getElementById('v2pack').value=10;v2PackOk();0"); await pg.wait_for_timeout(200)
        s = await sheet(); chk('asks how many BOXES, shows the pieces', 'boxes' in s.lower(), s[:300])
        await E("scQ(0,2);0"); chk('2 boxes = 20 pc on the button', '20 pc' in await E("document.getElementById('scQok').textContent"))
        await pg.locator('#scQok').click(); await pg.wait_for_timeout(200)
        chk('list: 6 + 20 = 26 of the same item, one line', await E(f"siLines.filter(l=>l.id==='{nid}').length===1&&siLines.find(l=>l.id==='{nid}').qty===26"))
        await scan(B3); s = await sheet()
        chk('next box scan is instant with box of 10', 'box of 10' in s.lower(), s[:200])
        await E("scSkip();0")

        print('5. Neighbouring number (a different product) is NOT matched')
        await E("_UPCDB={};_OCR='';0")
        await scan(U4); s = await sheet()
        chk('treated as a new barcode', 'New barcode' in s and '5603-2W 3' not in s.split('Possible')[0], s[:300])
        chk('no strong "Is it this one?" for it', 'Is it one of these?' not in s)
        await E("scSkip();0")

        print('6. Label reading: item already in the list (no duplicates)')
        await E("D.stock.push({id:'s_lux1',name:'Luxrite 2in round trim white',model:'LR25022',brand:'Luxrite',unit:'pc',qty:7});save();0")
        await E(f"_OCR={json.dumps(LUX_TXT)};0")
        await scan(UL); s = await sheet(); await shot('06_existing_by_part')
        chk('offers the existing item first ("Is it one of these?")', 'Is it one of these?' in s and 'Luxrite 2in round trim white' in s, s[:400])
        chk('reason: same part number', 'same part number' in s)
        n0 = await E("D.stock.length")
        await pg.locator('#v2cands .v2c').first.click(); await pg.wait_for_timeout(200)
        chk('tapping it links the barcode, no new item', await E("D.stock.length") == n0 and await E("Object.values(D.bc).some(m=>m.item==='s_lux1')"))
        await E("scSkip();0")

        print('7. Duplicate guard: "save as new" when that part number already exists')
        UL2 = '79388842695'; UL2 += ck(UL2)
        await E("D.stock.push({id:'s_lux2',name:'trim LR25022 white (old box)',unit:'pc',qty:1});save();0")
        await scan(UL2); await pg.wait_for_timeout(300)
        n0 = await E("D.stock.length")
        await pg.locator('#scLook .btn.gr').click(); await pg.wait_for_timeout(200)
        s = await sheet(); chk('first tap warns: you already have this part number', 'already have an item with this part number' in s, s[:300])
        chk('nothing created on the first tap', await E("D.stock.length") == n0)
        await E("scSkip();0")

        print('8. Unreadable label → no made-up name')
        await E(f"_OCR={json.dumps(JUNK_TXT)};0")
        await scan(UX); await pg.wait_for_timeout(300); s = await sheet(); await shot('08_unreadable')
        chk('says it could not identify the item', 'Could not identify this item for sure' in s, s[:300])
        chk('no name invented in the search box', await E("(document.getElementById('scFind').value||'').trim()===''"), await E("document.getElementById('scFind').value"))
        chk('junk words not offered as a name', 'BEA IMR' not in s)
        await E("scSkip();0")

        print('9. Unknown maker barcode + readable label: maker from the label text')
        await E("_OCR='EATON\\nType BR Circuit Breaker 1 Pole 20A\\n120/240 Vac 10 kA UL Listed\\nCat. No. BR120';0")
        UE = '61234500099'; UE += ck(UE)
        await scan(UE); await pg.wait_for_timeout(300)
        chk('maker Eaton, part BR120 read from the label', await E("document.getElementById('v2b').value==='Eaton'&&document.getElementById('v2p').value==='BR120'"), await sheet())
        await E("scSkip();0")

        print('10. AI fallback (only when the label reading is unsure, and only if AI is on)')
        await E("""window.EX_CFG=Object.assign({},window.EX_CFG||{},{ai:true});window._aiCalls=0;window._AI='';window.EX_sb={functions:{invoke:async(n,o)=>{_aiCalls++;return {data:{text:_AI}};}}};0""")
        await E("_OCR='LUTRON\\nDiva LED+ Dimmer\\nDVCL-153P-WH\\nWhite';0")
        UT = '61234500111'; UT += ck(UT)
        await scan(UT); await pg.wait_for_timeout(300)
        chk('clear label → AI not used', await E("_aiCalls===0"), await E("_aiCalls"))
        await E("scSkip();0")
        await E("""_OCR='LUTR0N  Diva\\nDVCL-153P-WH\\n';_AI='{"brand":"Lutron","part":"DVCL-153P-WH","description":"Diva LED+ Dimmer","color":"White","pack":0}';0""")
        UT2 = '61234500112'; UT2 += ck(UT2)
        await scan(UT2); await pg.wait_for_timeout(300); s = await sheet()
        await E("""_OCR='?? ~~ ||| ee';_AI='{"brand":"Lutron","part":"DVCL-153P-WH","description":"Diva LED+ Dimmer","color":"White","pack":0}';0""")
        await E("scSkip();0")
        UT3 = '61234500113'; UT3 += ck(UT3)
        await scan(UT3); await pg.wait_for_timeout(300); s = await sheet(); await shot('10_ai_unverified')
        chk('unsure label → AI asked', await E("_aiCalls")>=1)
        chk('AI answer NOT backed by the label → warning, marked "check it"', 'could not find this part number printed on the label' in s and 'check it' in s, s[:400])
        await E("scSkip();window.EX_CFG.ai=false;0")

        print('11. Same barcode on two items → the person picks')
        UC = '07847710099'; UC += ck(UC)
        await E(f"D.stock.push({{id:'s_c1',name:'GFCI 20A white',unit:'pc',qty:3,codes:['0{UC}']}},{{id:'s_c2',name:'GFCI 15A white',unit:'pc',qty:4,codes:['{UC}']}});save();0")
        await scan(UC); s = await sheet(); await shot('11_conflict')
        chk('shows "Pick the right item" with both', 'Pick the right item' in s and 'GFCI 20A' in s and 'GFCI 15A' in s, s[:300])
        await pg.locator('#scSheet .v2c', has_text='GFCI 15A').click(); await pg.wait_for_timeout(200)
        r = await E(f"(()=>{{const x=SV2.identify('{UC}',{{items:D.stock,maps:D.bc}});return x.status+':'+(x.item&&x.item.id)}})()")
        chk('after picking: barcode belongs only to the chosen item', r == 'known:s_c2', r)
        await E("scSkip();0")

        print('12. Wrong item → unlink and identify again')
        await scan(UC); await pg.wait_for_timeout(200)
        await E("_OCR='';0"); await E("scWrong();0"); await pg.wait_for_timeout(400)
        r = await E(f"SV2.identify('{UC}',{{items:D.stock,maps:D.bc}}).status")
        chk('barcode removed from the wrong item', r == 'new', r)
        chk('asks again which item it is', 'Which item is this?' in await sheet())
        await E("scSkip();0")

        print('13. A new BOX read from its label: box size comes from the label')
        BB = '3007847710555'; BB += ck(BB)
        await E(f"_OCR={json.dumps(SW_TXT.replace('5603-2W','5601-2W').replace('3-WAY','SINGLE POLE'))};_UPCDB={{}};0")
        await scan(BB, 'itf'); await pg.wait_for_timeout(300); s = await sheet(); await shot('13_new_box')
        chk('"In one box" filled from QTY 10 on the label', await E("(document.getElementById('v2n')||{}).value==='10'"), s[:400])
        await pg.locator('#scLook .btn.gr').click(); await pg.wait_for_timeout(200)
        s = await sheet(); chk('goes straight to "how many boxes"', 'boxes' in s.lower(), s[:200])
        bid = await E("D.stock.find(x=>x.model==='5601-2W').id")
        chk('box saved with 10 per box', await E(f"Object.values(D.bc).some(m=>m.item==='{bid}'&&m.pack===10&&m.level==='box')"))
        await E("scSkip();0")

        print('14. Same box scanned twice in a row is not counted twice')
        await scan(BB); await E(f"_scan('{BB}','itf');0"); await pg.wait_for_timeout(200)
        chk('second read within a moment is ignored (one sheet)', await E("document.querySelectorAll('#scQok').length===1"))
        await pg.locator('#scQok').click(); await pg.wait_for_timeout(200)
        chk('1 box = 10 counted once', await E(f"siLines.find(l=>l.id==='{bid}').qty===10"))

        print('15. Finish as New inventory → stock goes up by the counted pieces')
        q0 = await E(f"D.stock.find(x=>x.id==='{nid}').qty||0")
        await E("scanFinish();0"); await pg.wait_for_timeout(200); await E("scFrom('new');scComplete();0"); await pg.wait_for_timeout(500)
        q1 = await E(f"D.stock.find(x=>x.id==='{nid}').qty||0")
        chk('5603-2W stock went up by 26', q1 - q0 == 26, (q0, q1))
        chk('logged as New inventory', await E("D.stockLog.some(l=>l.kind==='in'&&/New inventory/.test(l.src||''))"))

        print('16. Spanish screens')
        await E("me().lang='es';0")
        es = await E("t('How many are in ONE box?')+'|'+t('Could not identify this item for sure. Search your items, or type the name.')")
        chk('V2 texts translated', es.startswith('¿Cuántos') and 'No se pudo' in es, es)
        chk(f'no page errors {errs[:2]}', not errs)
        await b.close()
    print(f"{len(ok)} passed, {len(bad)} failed")
    json.dump({'pass': len(ok), 'fail': len(bad), 'ok': ok, 'bad': bad}, open(os.path.join(HERE, 'out', 'flows_results.json'), 'w'), indent=1)
asyncio.run(main())
